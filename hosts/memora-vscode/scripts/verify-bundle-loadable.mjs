/**
 * 构建后冒烟：验证 `dist/extension/extension.js` 能被**真实加载**（模块求值不抛错）
 *
 * 存在的理由（2026-10-24 真机实测血训）：MCP SDK 的 ESM 产物 `client/stdio.js`
 * `import cross-spawn`，而 cross-spawn@7 是**纯 CJS**、内部 `require("child_process")`
 * ⇒ esbuild 输出 ESM 时把它包成 `__commonJS` + `__require(...)`。ESM 里没有
 * `require` ⇒ shim 抛 `Dynamic require of "child_process" is not supported`，
 * **扩展激活即失败**。而这条路径三类既有检查全看不见：
 *   - vitest 跑源码（node 直接解析 ESM/CJS 混合，cross-spawn 的 require 正常）；
 *   - `tsc --noEmit` 只看类型；
 *   - `pnpm run compile` 只报构建成功、体积复核也只看字节数。
 * ⇒ 唯一能证伪的是「把产物当 ESM 加载一遍」。本脚本就是那个动作。
 *
 * 做法：扫描产物里用到的 `vscode` 成员名 → 生成 stub → 用 `node:module` 的
 * `register()` 把 `vscode` 解析到 stub → `await import(产物)`。只验**求值期**
 * （不调 activate，那需要真宿主 API），足以捕获 CJS/ESM 形态类缺陷。
 */
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { register } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const HOST_ROOT = join(HERE, '..');
const BUNDLE = join(HOST_ROOT, 'dist', 'extension', 'extension.js');
const STUB_DIR = join(HOST_ROOT, 'dist', '.bundle-smoke');
const STUB = join(STUB_DIR, 'vscode-stub.mjs');

/** 从产物里提取 `vscodeN.member` 的第一级成员名（ESM namespace 不支持 Proxy 动态属性 ⇒ 必须静态导出） */
function collectVscodeMembers(source) {
  const members = new Set();
  const re = /\bvscode\d*\.([A-Za-z_$][\w$]*)/g;
  let match;
  while ((match = re.exec(source)) !== null) members.add(match[1]);
  return [...members].sort();
}

/** 生成 stub 源码（递归 Proxy：任意层级的属性访问/调用/构造都返回一个新的 stub） */
function renderStub(members) {
  return `// AUTO-GENERATED by scripts/verify-bundle-loadable.mjs — 勿手改、勿入库
const __stub = (name) => new Proxy(function () {}, {
  get: (_t, prop) => {
    if (prop === 'then' || prop === Symbol.iterator) return undefined; // 别被当成 thenable / 可迭代
    if (prop === Symbol.toPrimitive) return () => 0;
    if (prop === 'toString' || prop === 'valueOf') return () => name;
    return __stub(name + '.' + String(prop));
  },
  apply: () => __stub(name + '()'),
  construct: () => __stub('new ' + name),
  has: () => true,
});
${members.map((name) => `export const ${name} = __stub('${name}');`).join('\n')}
`;
}

function main() {
  let source;
  try {
    source = readFileSync(BUNDLE, 'utf8');
  } catch {
    console.error(`[BUNDLE:SMOKE] 产物不存在：${BUNDLE}（先跑 pnpm run compile）`);
    process.exit(1);
  }

  const members = collectVscodeMembers(source);
  mkdirSync(STUB_DIR, { recursive: true });
  writeFileSync(STUB, renderStub(members), 'utf8');

  register(new URL('vscode-stub-loader.mjs', pathToFileURL(join(HERE, 'x')).href).href);

  return import(pathToFileURL(BUNDLE).href).then(
    () => {
      console.log(
        `[BUNDLE:SMOKE] ✅ 产物加载通过：dist/extension/extension.js（vscode stub 成员 ${members.length} 个）`,
      );
    },
    (err) => {
      const message = String(err && err.message ? err.message : err);
      console.error('[BUNDLE:SMOKE] ❌ 产物加载失败——扩展在真机上会在激活阶段以同一错误崩溃：');
      console.error(`  ${message}`);
      if (message.includes('Dynamic require')) {
        console.error(
          '  判读：产物里存在 CJS 依赖的 `require()`，而 ESM 下 require 未定义。' +
            '修法 = esbuild banner 注入 createRequire（见 esbuild.config.mjs），' +
            '不是改业务代码、也不是把该依赖标 external。',
        );
      }
      process.exit(1);
    },
  );
}

await main();
